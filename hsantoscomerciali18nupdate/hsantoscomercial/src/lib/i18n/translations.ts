type Namespace = keyof typeof translations.pt;

export function t<N extends Namespace>(
  lang: Language,
  namespace: N,
  key: keyof (typeof translations)["pt"][N],
  vars?: Record<string, string | number>
): string {
  const dict = translations[lang] ?? translations.pt;
  const nsDict = (dict[namespace] ?? translations.pt[namespace]) as Record<string, string>;
  const fallback = (translations.pt[namespace] as Record<string, string>)[key as string];
  let str = nsDict[key as string] ?? fallback ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}

